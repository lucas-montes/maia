/** Replace every `<i data-lucide="name">` placeholder under `root` with SVGs. */
export function refreshIcons(root: ParentNode = document): void {
  // The registry is a subset of the full icon set; createIcons just looks up
  // names in it, so the cast is safe.
  createIcons({ icons: registry as Icons, nameAttr: "data-lucide", root: root as HTMLElement });
}
